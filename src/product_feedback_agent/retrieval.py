"""Persistent semantic retrieval over feedback and product-context collections.

Design notes:
- Embeddings are generated by us (via an injected Embedder) and passed to
  Chroma explicitly; collections are created with embedding_function=None
  so Chroma never tries to embed anything itself.
- Both collections use cosine distance (hnsw:space="cosine"), which pairs
  with the normalized embeddings produced by LocalEmbedder.
- feedback_id / section_id are used as Chroma record IDs, so re-indexing
  the same record/section is an upsert, not a duplicate insert.
- Metadata values that Chroma cannot store (None, non-primitive types) are
  omitted rather than replaced with an invented placeholder.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol, Sequence

import chromadb

from product_feedback_agent.embeddings import LocalEmbedder
from product_feedback_agent.schemas import ContextDocument, ContextSection, FeedbackRecord

DEFAULT_CHROMA_PATH = "data/local/chroma"
FEEDBACK_COLLECTION_NAME = "feedback"
CONTEXT_COLLECTION_NAME = "product_context"

_COSINE_COLLECTION_METADATA = {"hnsw:space": "cosine"}


class Embedder(Protocol):
    def embed_documents(self, texts: list[str]) -> list[list[float]]: ...

    def embed_query(self, text: str) -> list[float]: ...


@dataclass
class FeedbackSearchResult:
    feedback_id: str
    text: str
    metadata: dict[str, Any]
    distance: float


@dataclass
class ContextSearchResult:
    section_id: str
    document_id: str
    text: str
    metadata: dict[str, Any]
    distance: float


class SemanticRetrieval:
    """Owns the persistent Chroma client and the feedback/product_context collections."""

    def __init__(
        self,
        persist_directory: str | Path = DEFAULT_CHROMA_PATH,
        embedder: Embedder | None = None,
    ) -> None:
        self._embedder = embedder if embedder is not None else LocalEmbedder()
        self._client = chromadb.PersistentClient(path=str(persist_directory))
        self._feedback_collection = self._client.get_or_create_collection(
            name=FEEDBACK_COLLECTION_NAME,
            metadata=_COSINE_COLLECTION_METADATA,
            embedding_function=None,
        )
        self._context_collection = self._client.get_or_create_collection(
            name=CONTEXT_COLLECTION_NAME,
            metadata=_COSINE_COLLECTION_METADATA,
            embedding_function=None,
        )

    def index_feedback(self, records: Sequence[FeedbackRecord]) -> None:
        """Upsert feedback records into the feedback collection."""
        records = list(records)
        if not records:
            return

        ids = [record.feedback_id for record in records]
        documents = [record.text for record in records]
        embeddings = self._embedder.embed_documents(documents)
        metadatas = [_feedback_metadata(record) for record in records]

        self._feedback_collection.upsert(
            ids=ids, embeddings=embeddings, documents=documents, metadatas=metadatas
        )

    def index_context(
        self, items: ContextDocument | ContextSection | Sequence[ContextDocument | ContextSection]
    ) -> None:
        """Upsert product-context sections into the product_context collection.

        Accepts ContextDocument objects (indexing all of their sections, with
        filename/document_type metadata) or bare ContextSection objects
        (indexed without filename/document_type, since those live on the
        parent document).
        """
        if isinstance(items, (ContextDocument, ContextSection)):
            items = [items]

        sections_with_doc_info: list[tuple[ContextSection, str | None, str | None]] = []
        for item in items:
            if isinstance(item, ContextDocument):
                sections_with_doc_info.extend(
                    (section, item.filename, item.document_type) for section in item.sections
                )
            elif isinstance(item, ContextSection):
                sections_with_doc_info.append((item, None, None))
            else:
                raise TypeError(f"Unsupported item type for index_context: {type(item)!r}")

        if not sections_with_doc_info:
            return

        ids = [section.section_id for section, _, _ in sections_with_doc_info]
        documents = [section.text for section, _, _ in sections_with_doc_info]
        embeddings = self._embedder.embed_documents(documents)
        metadatas = [
            _context_metadata(section, filename, document_type)
            for section, filename, document_type in sections_with_doc_info
        ]

        self._context_collection.upsert(
            ids=ids, embeddings=embeddings, documents=documents, metadatas=metadatas
        )

    def search_feedback(self, query: str, top_k: int) -> list[FeedbackSearchResult]:
        """Semantically search indexed feedback, returning up to top_k results."""
        _validate_top_k(top_k)
        count = self._feedback_collection.count()
        if count == 0:
            return []

        results = self._feedback_collection.query(
            query_embeddings=[self._embedder.embed_query(query)],
            n_results=min(top_k, count),
            include=["documents", "metadatas", "distances"],
        )

        return [
            FeedbackSearchResult(
                feedback_id=feedback_id, text=text, metadata=dict(metadata or {}), distance=distance
            )
            for feedback_id, text, metadata, distance in zip(
                results["ids"][0], results["documents"][0], results["metadatas"][0], results["distances"][0]
            )
        ]

    def search_context(self, query: str, top_k: int) -> list[ContextSearchResult]:
        """Semantically search indexed product-context sections, returning up to top_k results."""
        _validate_top_k(top_k)
        count = self._context_collection.count()
        if count == 0:
            return []

        results = self._context_collection.query(
            query_embeddings=[self._embedder.embed_query(query)],
            n_results=min(top_k, count),
            include=["documents", "metadatas", "distances"],
        )

        return [
            ContextSearchResult(
                section_id=section_id,
                document_id=(metadata or {}).get("document_id", ""),
                text=text,
                metadata=dict(metadata or {}),
                distance=distance,
            )
            for section_id, text, metadata, distance in zip(
                results["ids"][0], results["documents"][0], results["metadatas"][0], results["distances"][0]
            )
        ]


def _validate_top_k(top_k: int) -> None:
    if top_k <= 0:
        raise ValueError("top_k must be positive")


def _feedback_metadata(record: FeedbackRecord) -> dict[str, Any]:
    metadata: dict[str, Any] = {"source": record.source}
    if record.segment is not None:
        metadata["segment"] = record.segment
    if record.product_area is not None:
        metadata["product_area"] = record.product_area
    if record.date is not None:
        metadata["date"] = record.date.isoformat()
    if record.customer_id is not None:
        metadata["customer_id"] = record.customer_id
    if record.rating is not None:
        metadata["rating"] = record.rating
    return metadata


def _context_metadata(
    section: ContextSection, filename: str | None, document_type: str | None
) -> dict[str, Any]:
    metadata: dict[str, Any] = {
        "document_id": section.document_id,
        "section_id": section.section_id,
        "section_index": section.section_index,
    }
    if filename is not None:
        metadata["filename"] = filename
    if document_type is not None:
        metadata["document_type"] = document_type
    if section.heading is not None:
        metadata["heading"] = section.heading
    return metadata
