"""Run the Stage 16 deterministic evaluation suite and write its report.

Usage:
    .\\.venv\\Scripts\\python.exe -m eval.run_evaluation

Writes `eval/evaluation_report.json` (machine-readable) and
`eval/evaluation_report.md` (human-readable) from the actually-measured
results of `eval.cases.run_all()`. No number in either report is invented:
every count is computed from the case results at run time. Exits non-zero if
any case fails, so this can also be used as a CI gate.

This script makes zero live Gemini calls, zero live GitHub mutations, and
has zero network dependency -- see eval/cases.py's module docstring.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from eval.cases import EvalCaseResult, run_all

_REPORT_DIR = Path(__file__).resolve().parent


def _category_totals(results: list[EvalCaseResult], category: str) -> tuple[int, int]:
    subset = [r for r in results if r.category == category]
    return sum(1 for r in subset if r.passed), len(subset)


def _violation_totals(results: list[EvalCaseResult]) -> tuple[int, int]:
    subset = [r for r in results if r.is_violation_check]
    return sum(1 for r in subset if r.passed), len(subset)


def summarize(results: list[EvalCaseResult]) -> dict:
    cases_passed = sum(1 for r in results if r.passed)
    cases_executed = len(results)

    grounding_passed, grounding_total = _category_totals(results, "grounding")
    safety_passed, safety_total = _category_totals(results, "safety")
    violations_caught, violations_total = _violation_totals(results)

    by_category: dict[str, dict[str, int]] = defaultdict(lambda: {"passed": 0, "total": 0})
    for r in results:
        by_category[r.category]["total"] += 1
        if r.passed:
            by_category[r.category]["passed"] += 1

    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "cases_passed": cases_passed,
        "cases_executed": cases_executed,
        "grounding_checks_passed": grounding_passed,
        "grounding_checks_total": grounding_total,
        "expected_validation_violations_caught": violations_caught,
        "expected_validation_violations_total": violations_total,
        "safety_cases_passed": safety_passed,
        "safety_cases_total": safety_total,
        "by_category": dict(by_category),
        "cases": [
            {
                "case_id": r.case_id,
                "requirement": r.requirement,
                "category": r.category,
                "is_violation_check": r.is_violation_check,
                "passed": r.passed,
                "detail": r.detail,
            }
            for r in results
        ],
        "constraints": {
            "live_gemini_calls_made": 0,
            "live_github_mutations_made": 0,
            "network_dependency": False,
        },
    }


def _write_json_report(summary: dict) -> Path:
    path = _REPORT_DIR / "evaluation_report.json"
    path.write_text(json.dumps(summary, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    return path


def _write_markdown_report(summary: dict) -> Path:
    path = _REPORT_DIR / "evaluation_report.md"

    lines: list[str] = []
    lines.append("# Stage 16 Deterministic Evaluation Report")
    lines.append("")
    lines.append(
        "Generated by `python -m eval.run_evaluation`. Every number below is measured "
        "by actually running the cases in `eval/cases.py` against the real, unmodified "
        "production code -- nothing here is estimated. No live Gemini call, live GitHub "
        "mutation, or network dependency occurs anywhere in this suite."
    )
    lines.append("")
    lines.append(f"Generated at (UTC): `{summary['generated_at_utc']}`")
    lines.append("")
    lines.append("## Measured Results")
    lines.append("")
    lines.append(f"- Cases passed / executed: **{summary['cases_passed']} / {summary['cases_executed']}**")
    lines.append(
        "- Grounding checks passed / total: "
        f"**{summary['grounding_checks_passed']} / {summary['grounding_checks_total']}**"
    )
    lines.append(
        "- Expected validation violations caught / total: "
        f"**{summary['expected_validation_violations_caught']} / {summary['expected_validation_violations_total']}**"
    )
    lines.append(
        f"- Safety cases passed / total: **{summary['safety_cases_passed']} / {summary['safety_cases_total']}**"
    )
    lines.append("")
    lines.append("## By Category")
    lines.append("")
    lines.append("| Category | Passed | Total |")
    lines.append("|---|---|---|")
    for category, counts in sorted(summary["by_category"].items()):
        lines.append(f"| {category} | {counts['passed']} | {counts['total']} |")
    lines.append("")
    lines.append("## Case Detail")
    lines.append("")
    lines.append("| Case | Requirement | Category | Violation Check | Result | Detail |")
    lines.append("|---|---|---|---|---|---|")
    for case in summary["cases"]:
        result_marker = "PASS" if case["passed"] else "**FAIL**"
        detail = case["detail"].replace("|", "\\|")
        lines.append(
            f"| {case['case_id']} | {case['requirement']} | {case['category']} | "
            f"{'yes' if case['is_violation_check'] else 'no'} | {result_marker} | {detail} |"
        )
    lines.append("")
    lines.append("## Explicitly Not Measured Here")
    lines.append("")
    lines.append(
        "This suite does not compute, and this report does not contain, any accuracy, "
        "precision, recall, or quality percentage, nor any latency number. Those are not "
        "produced by deterministic offline cases and are not claimed. Live Gemini call "
        "durations/token counts, when they exist, are recorded separately in "
        "`docs/results-log.md` from real, human-triggered smoke runs -- never from this "
        "offline suite."
    )
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> int:
    results = run_all()
    summary = summarize(results)

    json_path = _write_json_report(summary)
    md_path = _write_markdown_report(summary)

    print(f"Cases passed/executed: {summary['cases_passed']}/{summary['cases_executed']}")
    print(f"Grounding checks passed/total: {summary['grounding_checks_passed']}/{summary['grounding_checks_total']}")
    print(
        "Expected validation violations caught/total: "
        f"{summary['expected_validation_violations_caught']}/{summary['expected_validation_violations_total']}"
    )
    print(f"Safety cases passed/total: {summary['safety_cases_passed']}/{summary['safety_cases_total']}")
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")

    failed = [r for r in results if not r.passed]
    if failed:
        print("\nFAILED CASES:")
        for r in failed:
            print(f"  {r.case_id} ({r.requirement}): {r.detail}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
